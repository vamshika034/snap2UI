import io
import zipfile
from typing import Dict, Any

class ProjectExporter:
    """
    Packages generated Android source files, XML layouts, Gradle configuration,
    and README into a downloadable ZIP archive.
    """
    def __init__(self):
        pass

    def create_project_zip(self, project_name: str, compose_code: str, xml_code: str) -> bytes:
        zip_buffer = io.BytesIO()
        with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zip_file:
            # Add README
            readme_content = f"""# {project_name} - Generated by Snap2UI
Exported Android Jetpack Compose & XML Project.

## Structure:
- app/src/main/java/com/Snap2UI/app/ui/generated/ReconstructedScreen.kt
- app/src/main/res/layout/activity_main.xml
- build.gradle.kts
"""
            zip_file.writestr("README.md", readme_content)
            zip_file.writestr("app/src/main/java/com/Snap2UI/app/ui/generated/ReconstructedScreen.kt", compose_code)
            zip_file.writestr("app/src/main/res/layout/activity_main.xml", xml_code)
            zip_file.writestr("build.gradle.kts", "plugins { id('com.android.application') }\nandroid { compileSdk = 35 }")

        zip_buffer.seek(0)
        return zip_buffer.getvalue()
